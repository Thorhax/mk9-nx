#!/usr/bin/env python3
"""banjo-nx (deko3d renderer, docs/deko3d-renderer.md section 5): one of Renut's host shaders for the deko3d back end.

    python tools/deko3d_host_shader.py --dxc dxc.exe --spirv-cross spirv-cross.exe --uam uam.exe
        --profile vs_6_0 --stem present_vs --src shaders/host/present_vs.hlsl --out host_shaders/present_vs.deko3d.h

DXC (SPIR-V, -DBANJO_DEKO3D, D3D clip space: no -fvk-invert-y), SPIRV-Cross (Vulkan GLSL 4.60), tools/deko3d_glsl.py,
uam (the default variant's DKSH). The header holds g_<stem>_deko3d: a plume::Deko3DShaderBlob (16 bytes: "BDK3", stage,
GLSL size, DKSH size), the GLSL, the DKSH. The build tools come from tools/deko3d_build_tools.sh.
"""
import argparse
import os
import struct
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import deko3d_glsl  # noqa: E402

STAGES = {'vs': ('vert', 0), 'gs': ('geom', 3), 'ps': ('frag', 4), 'cs': ('comp', 5)}


def main():
    ap = argparse.ArgumentParser()
    for k in ('dxc', 'spirv-cross', 'uam', 'profile', 'stem', 'src', 'out'):
        ap.add_argument('--' + k, required=True)
    a = ap.parse_args()
    kind = a.profile[:2]
    if kind not in STAGES:
        sys.exit(f'deko3d_host_shader: profile {a.profile}')
    stage_name, stage = STAGES[kind]
    with tempfile.TemporaryDirectory() as tmp:
        spv = os.path.join(tmp, a.stem + '.spv')
        vk = os.path.join(tmp, a.stem + '.vk.glsl')
        dksh = os.path.join(tmp, a.stem + '.dksh')
        r = subprocess.run([a.dxc, '-T', a.profile, '-E', 'main', '-HV', '2021', '-all-resources-bound',
                            '-Wno-ignored-attributes', '-spirv', '-fvk-use-dx-layout', '-DBANJO_DEKO3D', a.src, '-Fo', spv],
                           capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f'deko3d_host_shader: DXC failed for {a.src}:\n{r.stdout}{r.stderr}')
        r = subprocess.run([a.spirv_cross, spv, '--version', '460', '--vulkan-semantics', '--relax-nan-checks',
                            '--output', vk], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f'deko3d_host_shader: SPIRV-Cross failed for {a.src}:\n{r.stdout}{r.stderr}')
        try:
            glsl, _ = deko3d_glsl.convert(open(vk, encoding='utf-8').read(), stage_name, deko3d_glsl.DEFAULT_UBO_MAP)
        except deko3d_glsl.Unsupported as e:
            sys.exit(f'deko3d_host_shader: {a.src}: {e}')
        glsl_path = os.path.join(tmp, a.stem + '.glsl')
        with open(glsl_path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(glsl)
        r = subprocess.run([a.uam, '-s', stage_name, '-o', dksh, glsl_path], capture_output=True, text=True)
        if r.returncode != 0 or not os.path.isfile(dksh):
            sys.exit(f'deko3d_host_shader: uam failed for {a.src}:\n{r.stdout}{r.stderr}')
        warnings = [l for l in (r.stdout + r.stderr).split('\n') if 'warning' in l.lower()]
        if warnings:
            sys.exit(f'deko3d_host_shader: uam warns for {a.src} (fix the shader):\n' + '\n'.join(warnings))
        code = open(dksh, 'rb').read()
    text = glsl.encode('utf-8')
    blob = struct.pack('<IIII', 0x334B4442, stage, len(text), len(code)) + text + code
    lines = [f'// Generated by tools/deko3d_host_shader.py from {os.path.basename(a.src)} ({a.profile}): '
             f'{len(text)} bytes of GLSL, {len(code)} bytes of DKSH.',
             '#pragma once', '#include <cstdint>', f'static const uint8_t g_{a.stem}_deko3d[] = {{']
    for i in range(0, len(blob), 24):
        lines.append('    ' + ', '.join(f'0x{b:02X}' for b in blob[i:i + 24]) + ',')
    lines.append('};')
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out + '.tmp', 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    os.replace(a.out + '.tmp', a.out)


if __name__ == '__main__':
    main()
