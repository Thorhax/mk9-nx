"""Census build: hooks for every Direct3D-range function without a hook of its own, and the hooked list for
   direct_calls.py.  python d3d_census_build.py [--restore]
   Writes out/census/sa2_d3d_census_all.cpp + out/census/hooked.txt, then runs direct_calls.py --redo --hooked-list.
   Configure the PC build with -DSA2_EXTRA_SOURCES=<abs path of the .cpp>. --restore: direct_calls.py --redo (normal)."""
import glob, os, re, subprocess, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
GEN = ROOT + '/app/generated/default'
OUT = ROOT + '/out/census'
if '--restore' in sys.argv:
    open(ROOT + '/out/extra_hooks.txt', 'w').write('')  # emptied, not deleted
    subprocess.run([sys.executable, ROOT + '/tools/direct_calls.py', '--redo'], check=True)
    sys.exit(0)
DEF = re.compile(r'^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\) \{$')
funcs = set()
for f in glob.glob(GEN + '/sa2_recomp.*.cpp'):
    for ln in open(f, encoding='utf-8', errors='ignore'):
        m = DEF.match(ln)
        if m and 0x82540000 <= int(m.group(1), 16) < 0x82570000: funcs.add(m.group(1))
# hooks really defined in the sources (not mere mentions)
HOOK = re.compile(r'(?:REX_HOOK_RAW\(sub_|SA2_HOT_HOOK_COPY\(|SA2_COPY_FOR_HOOK\(|SA2_HOT_HOOK_UNGUARDED\(|SA2_HOT_HOOK\(|SA2_TRACE_HOOK\(\d+, )([0-9A-F]{8})')
defined = set()
for d in (ROOT + '/app/src', ROOT + '/sdk/src'):
    for dp, _, fs in os.walk(d):
        for f in fs:
            if f.endswith(('.cpp', '.h', '.inc')):
                defined |= set(HOOK.findall(open(os.path.join(dp, f), encoding='utf-8', errors='ignore').read()))
SEGMENT = '8254EBB8'
census = sorted(funcs - defined)
os.makedirs(OUT, exist_ok=True)
with open(OUT + '/sa2_d3d_census_all.cpp', 'w', newline='\n') as o:
    o.write('// Generated by the scratchpad d3d_census_build.py: the Direct3D census build\'s hooks (diagnostic only).\n')
    o.write('#include <rex/hook.h>\n#include <rex/ppc.h>\n\n#include "me/sa2_d3d_api.h"\n\n')
    for a in census:
        o.write(('SA2_D3D_CENSUS_SEGMENT_HOOK(%s)\n' if a == SEGMENT else 'SA2_D3D_CENSUS_HOOK(%s)\n') % a)
sys.path.insert(0, ROOT + '/tools')
# The census hooks live outside the scanned sources: out/extra_hooks.txt names them for every direct_calls.py run
# (post_codegen included); --restore empties it.
open(ROOT + '/out/extra_hooks.txt', 'w').write('\n'.join('sub_' + a for a in census) + '\n')
print(f'{len(funcs)} functions in the range, {len(funcs & defined)} hooked already, {len(census)} census hooks')
subprocess.run([sys.executable, ROOT + '/tools/direct_calls.py', '--redo'], check=True)
